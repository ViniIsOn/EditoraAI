package com.vini.editoraai;

import android.graphics.Bitmap;
import android.graphics.Canvas;
import android.graphics.Color;
import android.graphics.Paint;
import android.graphics.Typeface;

import androidx.media3.common.OverlaySettings;
import androidx.media3.common.util.UnstableApi;
import androidx.media3.effect.BitmapOverlay;
import androidx.media3.effect.StaticOverlaySettings;

import java.util.ArrayList;
import java.util.List;

/** Real caption graphics burned into the MP4, timed to the selected clip. */
@UnstableApi
public final class CaptionOverlay extends BitmapOverlay {
    private final List<Caption> captions;
    private final long trimStartMs;
    private final StaticOverlaySettings settings;
    private Bitmap bitmap;
    private String lastText = null;

    public CaptionOverlay(List<Caption> captions, long trimStartMs) {
        this.captions = new ArrayList<>(captions);
        this.trimStartMs = trimStartMs;
        this.settings = new StaticOverlaySettings.Builder()
                .setBackgroundFrameAnchor(0f, -0.63f)
                .setOverlayFrameAnchor(0f, 0f)
                .build();
    }

    @Override public OverlaySettings getOverlaySettings(long timeUs) { return settings; }

    @Override public Bitmap getBitmap(long presentationTimeUs) {
        long ms = trimStartMs + presentationTimeUs / 1000;
        String selected = "";
        for (Caption c : captions) {
            if (c.contains(ms)) { selected = c.text; break; }
        }
        if (bitmap == null || !selected.equals(lastText)) {
            lastText = selected;
            // A reusable ARGB image: empty captions are fully transparent.
            if (bitmap == null) bitmap = Bitmap.createBitmap(700, 230, Bitmap.Config.ARGB_8888);
            Canvas canvas = new Canvas(bitmap);
            canvas.drawColor(Color.TRANSPARENT, android.graphics.PorterDuff.Mode.CLEAR);
            if (!selected.isEmpty()) drawCaption(canvas, selected);
        }
        return bitmap;
    }

    private void drawCaption(Canvas canvas, String content) {
        Paint paint = new Paint(Paint.ANTI_ALIAS_FLAG);
        paint.setTypeface(Typeface.create("sans-serif-condensed", Typeface.BOLD));
        paint.setTextAlign(Paint.Align.CENTER);
        paint.setTextSize(49);
        String[] lines = wrap(content.toUpperCase(java.util.Locale.forLanguageTag("pt-BR")), paint, 650);
        float lineHeight = 58;
        float y = 115 - (lines.length - 1) * lineHeight / 2f;
        for (String line : lines) {
            paint.setStyle(Paint.Style.STROKE);
            paint.setStrokeWidth(9f);
            paint.setStrokeJoin(Paint.Join.ROUND);
            paint.setColor(Color.BLACK);
            canvas.drawText(line, 350, y, paint);
            paint.setStyle(Paint.Style.FILL);
            paint.setColor(Color.WHITE);
            canvas.drawText(line, 350, y, paint);
            y += lineHeight;
        }
    }

    private String[] wrap(String input, Paint paint, int maxWidth) {
        String[] tokens = input.replace('\n', ' ').trim().split("\\s+");
        List<String> lines = new ArrayList<>();
        String current = "";
        for (String word : tokens) {
            String candidate = current.isEmpty() ? word : current + " " + word;
            if (paint.measureText(candidate) > maxWidth && !current.isEmpty()) {
                lines.add(current);
                current = word;
            } else current = candidate;
        }
        if (!current.isEmpty()) lines.add(current);
        // Avoid text overflowing vertically: smaller captions should be generated by transcription.
        if (lines.size() > 3) {
            paint.setTextSize(37);
            return wrapWithLimit(input, paint, maxWidth, 4);
        }
        return lines.toArray(new String[0]);
    }

    private String[] wrapWithLimit(String input, Paint paint, int maxWidth, int maxLines) {
        List<String> lines = new ArrayList<>();
        String line = "";
        for (String word : input.split("\\s+")) {
            String attempt = line.isEmpty() ? word : line + " " + word;
            if (paint.measureText(attempt) > maxWidth && !line.isEmpty() && lines.size() < maxLines - 1) {
                lines.add(line);
                line = word;
            } else line = attempt;
        }
        if (!line.isEmpty()) lines.add(line);
        return lines.toArray(new String[0]);
    }
}
